"""爬虫调度层 —— **唯一**接触爬虫的地方。

别处只看到"一个 key + 一条命令 → 一份 data"。爬虫是子进程、有超时、会失败，
这些细节全部烂在这一层里，不许往上传。

    runner.py     跑子进程、卡硬超时、解析单行 JSON 信封
    registry.py   有哪些源、源的 meta 与能力、能力路由（唯一通往爬虫的关口）
    guard.py      每站的并发上限与熔断（源站出问题时别拖垮本站）
    validate.py   把爬虫的输出塞进契约模型，不合格就拒收

为什么是子进程而不是 import 进来？因为威胁模型是**稳定性**：
某个爬虫写出死循环或者卡在源站上，不能把整个 API 一起拖死。
同理，:mod:`app.crawler.guard` 管的是"源站把每个请求都拖满超时"
这一类问题。两者一个防子进程，一个防等待。
注意区分名字：顶层 ``crawler/`` 是爬虫**本体**，这里的 ``app/crawler/``
是后端**调度**爬虫的代码。
"""
